export async function generateCareerRoadmapAi({ careerTitle, currentSkills = [] }) {
  const prompt = `Generate a structured, 7-step career learning roadmap for an undergraduate student aiming to become a "${careerTitle}".
Current student skills: ${currentSkills.join(', ') || 'Basic programming'}.

Return ONLY a valid JSON object matching this exact schema, without markdown code fences or backticks:
{
  "title": "${careerTitle} Career Roadmap",
  "summary": "Brief 2-sentence roadmap description",
  "stages": [
    {
      "step": 1,
      "skill_or_topic": "Topic Name",
      "description": "Clear explanation of what to learn and why",
      "resources": "Recommended courses, books, or documentation",
      "difficulty": "Beginner | Intermediate | Advanced"
    }
  ]
}`;

  if (model) {
    try {
      const res = await model.generateContent(prompt);
      const text = res.response.text().trim();
      const cleaned = text.replace(/^```json\s*/i, '').replace(/^```\s*/i, '').replace(/\s*```$/i, '').trim();
      return JSON.parse(cleaned);
    } catch (err) {
      console.warn('[AI] Gemini roadmap generation failed, using fallback:', err.message);
    }
  }

  // Fallback roadmap generator
  return getFallbackRoadmap(careerTitle);
}

