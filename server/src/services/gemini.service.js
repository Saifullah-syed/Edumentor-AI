// 1. Advisor Chat Response
export async function generateAdvisorResponse({ studentProfile, message, chatHistory = [] }) {
  const disclaimerNotice = '⚠️ [Disclaimer: This advice is generated by EduMentor AI. Official course registrations, prerequisites, and degree audits should always be confirmed with your university academic department advisor.]';

  const systemPrompt = `You are EduMentor AI, an expert, encouraging, and academically rigorous university academic and career advisor.
Student Context:
- Name: ${studentProfile.name || 'Student'}
- Program: ${studentProfile.program || 'Undergraduate Degree'} (${studentProfile.degree || 'B.S.'})
- University: ${studentProfile.university || 'University'}
- GPA: ${studentProfile.gpa || 'N/A'}
- Academic Progress: ${studentProfile.academic_progress || 0}%
- Target Career: ${studentProfile.target_career_title || 'Undecided'}
- Completed Courses: ${studentProfile.completed_courses?.join(', ') || 'None recorded'}
- In-Progress Courses: ${studentProfile.in_progress_courses?.join(', ') || 'None recorded'}
- Current Skills: ${studentProfile.skills?.map(s => `${s.name} (${s.proficiency})`).join(', ') || 'None recorded'}

Advisor Principles:
1. Provide structured, actionable, and personalized advice based on their current academic standing, courses, and skills.
2. If asked about what courses or skills to take next, prioritize filling gaps for their target career.
3. If asked about career roadmaps or projects, suggest realistic portfolio-ready capstone projects.
4. If the question is outside academic and career advising, politely guide the student back to educational guidance.
5. Format responses cleanly using markdown bullet points, bold highlights, and clear sections.
6. Keep recommendations realistic and encouraging.`;

  if (model) {
    try {
      const historyContents = chatHistory.slice(-6).map(m => ({
        role: m.sender === 'user' ? 'user' : 'model',
        parts: [{ text: m.content.replace(disclaimerNotice, '').trim() }],
      }));

      const chat = model.startChat({
        history: [
          { role: 'user', parts: [{ text: `System Instruction:\n${systemPrompt}` }] },
          { role: 'model', parts: [{ text: 'Understood. I am EduMentor AI and ready to provide personalized, structured guidance for this student.' }] },
          ...historyContents,
        ],
      });

      const result = await chat.sendMessage(message);
      const text = result.response.text();
      return {
        content: `${text}\n\n${disclaimerNotice}`,
        isMockAi: false,
      };
    } catch (err) {
      console.warn('[AI] Gemini chat generation failed, falling back to local advisor:', err.message);
    }
  }

  // Intelligent deterministic advisor fallback
  return {
    content: generateFallbackAdvisorResponse(studentProfile, message, disclaimerNotice),
    isMockAi: true,
  };
}

